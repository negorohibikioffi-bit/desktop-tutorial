-- AXIA 金消予定日(自動更新版) DBを最初から作り直す。Supabase の SQL Editor で1回だけ実行。
-- ※ axia_kinsho_auto 系の2テーブルだけを作り直す(元の axia_kinsho には触らない)。
drop table if exists public.axia_kinsho_auto cascade;
drop table if exists public.axia_kinsho_auto_settings cascade;

create table public.axia_kinsho_auto (
  id bigint generated by default as identity primary key,
  month text not null,                 -- 'YYYY-MM'
  name text not null default '',
  fields jsonb not null default '{}'::jsonb,
  sort_order numeric default 0,
  mail_id text unique,                 -- 取込済みメールID(重複防止)
  cust text,                           -- 顧客キー(メール照合用)
  prop text,                           -- 物件キー(メール照合用)
  created_at timestamptz default now()
);
create index axia_kinsho_auto_cust_idx on public.axia_kinsho_auto (cust);

create table public.axia_kinsho_auto_settings (
  id int primary key,
  settings jsonb,
  updated_at timestamptz default now()
);

alter table public.axia_kinsho_auto enable row level security;
alter table public.axia_kinsho_auto_settings enable row level security;
create policy "anon all" on public.axia_kinsho_auto for all using (true) with check (true);
create policy "anon all" on public.axia_kinsho_auto_settings for all using (true) with check (true);

alter publication supabase_realtime add table public.axia_kinsho_auto, public.axia_kinsho_auto_settings;
